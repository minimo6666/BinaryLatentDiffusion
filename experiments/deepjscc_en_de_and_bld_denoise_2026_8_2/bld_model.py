"""Experiment-local BLD variant trained with symbol-level QAM/AWGN samples."""

from __future__ import annotations

import torch

from common import BLD_ROOT  # noqa: F401  (also installs the project import path)
from models.binarylatent_dsc import BinaryDiffusionDSC
from utils.m_qam_awgn_util import make_code_noise_single


class ExactQAMAWGNBinaryDiffusionDSC(BinaryDiffusionDSC):
    """Use exact QAM -> AWGN -> hard-demapping for the training observation.

    The original BLD implementation samples independent Bernoulli bit flips from
    a theoretical average BER. Here, training X_t is generated by the same
    symbol-level channel implementation used at evaluation time. The analytical
    transition remains in use for the reverse diffusion posterior.
    """

    def q_sample(self, x_0: torch.Tensor, t: torch.Tensor) -> torch.Tensor:
        # Reverse diffusion calls q_sample with a final binary-probability axis.
        # Keep the analytical transition for that case.
        if x_0.ndim == 4 and x_0.shape[-1] == 2:
            return super().q_sample(x_0, t)

        snrs = self.Eb_N0_dB_values.to(device=x_0.device)
        noisy = []
        with torch.no_grad():
            for sample_index in range(x_0.shape[0]):
                snr = float(snrs[t[sample_index]].item())
                noisy.append(
                    make_code_noise_single(
                        x_0[sample_index],
                        eb_n0_db=snr,
                        qam_order=self.qam_order,
                        device=x_0.device,
                    )
                )
        x_t = torch.stack(noisy, dim=0).to(dtype=x_0.dtype)
        self._last_channel_ber = float(((x_t > 0.5) != (x_0 > 0.5)).float().mean().item())
        self._last_snr_mean = float(snrs[t].mean().item())
        return x_t

    def _train_loss(self, *args, **kwargs):
        stats = super()._train_loss(*args, **kwargs)
        stats["channel_ber"] = getattr(self, "_last_channel_ber", float("nan"))
        stats["snr_mean_db"] = getattr(self, "_last_snr_mean", float("nan"))
        return stats

    @torch.no_grad()
    def predict_x0(self, x_t: torch.Tensor, timestep: int) -> torch.Tensor:
        """Fast one-pass X0 prediction, useful for smoke tests and ablation."""
        t = torch.full(
            (x_t.shape[0],), int(timestep), dtype=torch.long, device=x_t.device
        )
        logits = self._denoise_fn(x_t, time_steps=t)
        if self.p_flip:
            logits = x_t * (-logits) + (1.0 - x_t) * logits
        return (logits > 0.0).to(dtype=x_t.dtype)
